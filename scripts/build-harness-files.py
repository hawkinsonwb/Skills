#!/usr/bin/env python3
"""Generate skill-only plugin metadata and discovery rules from canonical sources."""

import argparse
import json
from pathlib import Path


def render(root):
    metadata = json.loads((root / '.claude-plugin/plugin.json').read_text())
    context = (root / 'docs/harness-context.md').read_text().rstrip()
    catalog = []
    for path in sorted((root / 'skills').glob('*/SKILL.md')):
        fields = dict(line.split(':', 1) for line in path.read_text().split('---', 2)[1].splitlines() if ':' in line)
        catalog.append(f"- `{fields['name'].strip()}`: {fields['description'].strip()}")
    context += '\n\n## Available skills\n\n' + '\n'.join(catalog) + '\n'
    generated = '<!-- Generated by scripts/build-harness-files.py; edit docs/harness-context.md or canonical skills. -->\n\n'
    outputs = {}

    def emit(path, value):
        outputs[path] = json.dumps(value, indent=2) + '\n'

    emit('.codex-plugin/plugin.json', {
        **metadata, 'skills': './skills/',
        'interface': {'displayName': 'Hawkinsonwb Skills', 'shortDescription': 'Product planning, delivery, and review',
                      'developerName': 'Brandon Hawkinson', 'category': 'Productivity',
                      'capabilities': ['Instructions'], 'websiteURL': metadata['repository']},
    })
    emit('.agents/plugins/marketplace.json', {
        'name': metadata['name'], 'interface': {'displayName': 'Hawkinsonwb Skills'},
        'plugins': [{'name': metadata['name'], 'source': {'source': 'local', 'path': './'},
                     'policy': {'installation': 'AVAILABLE', 'authentication': 'ON_INSTALL'},
                     'category': 'Productivity'}],
    })
    for path in ('.qoder-plugin/plugin.json', '.devin-plugin/plugin.json'):
        emit(path, {**metadata, 'skills': './skills/'})
    emit('plugin.json', {'name': metadata['name'], 'version': metadata['version'],
                         'description': metadata['description'], 'license': metadata['license']})
    marketplace = json.loads((root / '.claude-plugin/marketplace.json').read_text())
    emit('.grok-plugin/marketplace.json', marketplace)
    emit('gemini-extension.json', {'name': metadata['name'], 'version': metadata['version'],
                                  'description': metadata['description'], 'contextFileName': 'AGENTS.md'})
    emit('package.json', {'name': '@hawkinsonwb/skills', 'version': metadata['version'], 'private': True,
                         'description': metadata['description'], 'license': metadata['license'],
                         'repository': {'type': 'git', 'url': metadata['repository'] + '.git'},
                         'keywords': ['pi-package', 'agent-skills'], 'files': ['skills/', 'LICENSE'],
                         'pi': {'skills': ['./skills'], 'extensions': [], 'prompts': [], 'themes': []}})
    for path in ('.clinerules/hawkinsonwb-skills.md', '.qoder/rules/hawkinsonwb-skills.md',
                 '.agents/rules/hawkinsonwb-skills.md', 'AGENTS.md'):
        outputs[path] = generated + context
    outputs['AGENTS.md'] += '\n' + (root / 'docs/repository-conventions.md').read_text()
    outputs['.cursor/rules/hawkinsonwb-skills.mdc'] = '---\ndescription: Discover Hawkinsonwb planning, delivery, and review skills.\nalwaysApply: true\n---\n\n' + generated + context
    outputs['.kiro/steering/hawkinsonwb-skills.md'] = '---\ninclusion: always\n---\n\n' + generated + context
    outputs['.windsurf/rules/hawkinsonwb-skills.md'] = '---\ntrigger: always_on\n---\n\n' + generated + context
    outputs['.devin/rules/hawkinsonwb-skills.md'] = outputs['.windsurf/rules/hawkinsonwb-skills.md']
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Check generated files without modifying them.')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    outputs = render(root)
    stale = []
    for name, content in outputs.items():
        path = root / name
        if not path.exists() or path.read_text() != content:
            stale.append(name)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content)
    if args.check and stale:
        parser.exit(1, 'Stale harness files:\n' + '\n'.join(stale) + '\nRun python3 scripts/build-harness-files.py\n')
    print(f'{len(outputs)} harness files ' + ('verified.' if args.check else 'generated.'))


if __name__ == '__main__':
    main()
